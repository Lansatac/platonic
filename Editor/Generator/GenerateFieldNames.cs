#nullable enable

using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Platonic.Core;
using UnityEditor;
using UnityEngine;

namespace Platonic.Editor.Generator
{
    public class GenerateFieldNames : AssetPostprocessor
    {
        private static void OnPostprocessAllAssets(
            string[] importedAssets,
            string[] deletedAssets,
            string[] movedAssets,
            string[] movedFromAssetPaths)
        {
            var affectedFieldNames = FilterAffectedFieldNames(
                importedAssets,
                movedAssets,
                path => AssetDatabase.LoadAssetAtPath<FieldNames>(path));

            if (affectedFieldNames.Count > 0)
            {
                GenCode(affectedFieldNames);
            }
        }

        public static List<FieldNames> FilterAffectedFieldNames(
            IEnumerable<string> importedAssets,
            IEnumerable<string> movedAssets,
            Func<string, FieldNames?> loadAssetAtPath)
        {
            var affected = new HashSet<FieldNames>();

            foreach (var path in importedAssets)
            {
                if (string.IsNullOrEmpty(path) || !path.EndsWith(".asset", StringComparison.OrdinalIgnoreCase))
                    continue;

                var fieldNames = loadAssetAtPath(path);
                if (fieldNames != null)
                {
                    affected.Add(fieldNames);
                }
            }

            foreach (var path in movedAssets)
            {
                if (string.IsNullOrEmpty(path) || !path.EndsWith(".asset", StringComparison.OrdinalIgnoreCase))
                    continue;

                var fieldNames = loadAssetAtPath(path);
                if (fieldNames != null)
                {
                    affected.Add(fieldNames);
                }
            }

            return affected.ToList();
        }

        public static List<FieldNames> GetAllFieldNames()
        {
            var list = new List<FieldNames>();
            var assetIds = AssetDatabase.FindAssets("t:FieldNames");

            foreach (var id in assetIds)
            {
                var assetPath = AssetDatabase.GUIDToAssetPath(id);

                var names = AssetDatabase.LoadAssetAtPath<FieldNames>(assetPath);
                if (names != null)
                {
                    list.Add(names);
                }
            }

            return list;
        }

        [MenuItem("Platonic/Generate Fields Names")]
        public static void GenCode()
        {
            var fieldNames = GetAllFieldNames();
            GenCode(fieldNames);
        }

        public static void GenCode(IEnumerable<FieldNames> allNames, string? hash = null)
        {
            var anyChanged = false;
            foreach (var names in allNames)
            {
                if (names == null) continue;

                var generatedFile =
                    new FileInfo($"{Path.Combine("Assets/" + names.OutputPath, names.name)}.generated.cs");
                generatedFile.Directory!.Create();
                Debug.Log($"Generating {generatedFile.FullName}");

                var newContent = GenerateSource(names);

                var existingContent = "";
                if (generatedFile.Exists)
                {
                    using var readStream = generatedFile.OpenText();
                    existingContent = readStream.ReadToEnd();
                }

                // Only write if content has changed
                if (existingContent == newContent) continue;
                using var writeStream = generatedFile.OpenWrite();
                writeStream.SetLength(0); //overwrite existing
                using var writer = new StreamWriter(writeStream);
                writer.Write(newContent);
                Debug.Log($"Updated {generatedFile.FullName}");
                anyChanged = true;
            }

            if (anyChanged)
            {
                AssetDatabase.Refresh();
                AssetDatabase.SaveAssets();
            }
        }

        public static string GenerateSource(FieldNames names)
        {
            StringBuilder source = new StringBuilder(
                "#nullable enable\n" +
                "// File generated by Platonic. Do not modify manually, changes will be lost\n");

            var usings = new HashSet<string> { "Platonic", "Platonic.Core", "UnityEngine" };
            if (names.Names != null)
            {
                foreach (var name in names.Names)
                {
                    if (IsEnumerable(name))
                    {
                        usings.Add("System.Collections.Generic");
                        break;
                    }
                }
            }

            if (names.AdditionalUsings != null)
            {
                foreach (var additionalUsing in names.AdditionalUsings)
                {
                    if (!string.IsNullOrWhiteSpace(additionalUsing))
                    {
                        usings.Add(additionalUsing);
                    }
                }
            }

            foreach (var u in usings.OrderBy(x => x))
            {
                source.AppendLine($"using {u};");
            }

            source.Append("\n" +
                          $"namespace {names.Namespace}\n" +
                          "{\n" +
                          "#if UNITY_EDITOR\n" +
                          "\tusing UnityEditor;\n" +
                          "\t[InitializeOnLoad]\n" +
                          "#endif\n" +
                          $"\tpublic static class {names.ClassName}\n" +
                          "\t{\n" +
                          "\t\t[RuntimeInitializeOnLoadMethod(RuntimeInitializeLoadType.SubsystemRegistration)]\n" +
                          "\t\tprivate static void Init(){}" +
                          "\n\n");

            HashSet<string> usedNames = new();
            if (names.Names != null)
            {
                foreach (var name in names.Names)
                {
                    if (!usedNames.Contains(name.Name))
                    {
                        var fieldType = GetFieldType(name);
                        source.AppendLine(
                            $"\t\tpublic static readonly FieldName<{fieldType}> {name.Name} = Platonic.Core.Names.Register<{fieldType}>(\"{names.Namespace}.\" + nameof({name.Name}));");
                        usedNames.Add(name.Name);
                    }
                    else
                    {
                        Debug.LogWarning($"Duplicate name {name.Name}!");
                    }
                }
            }

            source.AppendLine("\t}");

            source.AppendLine();
            source.AppendLine();

            source.AppendLine("\tpublic static class NameExtensions");
            source.AppendLine("\t{");

            if (names.Names != null)
            {
                foreach (var name in names.Names)
                {
                    var fieldType = GetFieldType(name);
                    source.AppendLine(
                        $"\t\tpublic static {fieldType} Get_{name.Name}(this IData data) {{return data.GetField({names.ClassName}.{name.Name}).Value;}}");
                }
            }

            source.AppendLine("\t}");

            source.AppendLine("}");

            return source.ToString();
        }

        private static string GetFieldType(SerializableFieldNameDefinition name)
        {
            var fieldType = GetElementFieldType(name);
            if (IsEnumerable(name))
            {
                fieldType = $"IEnumerable<{fieldType}>";
            }

            return name.Nullable && !fieldType.EndsWith("?") ? $"{fieldType}?" : fieldType;
        }

        private static string GetElementFieldType(SerializableFieldNameDefinition name)
        {
            return name.Type switch
            {
                SerializableFieldNameDefinition.FieldType.custom => name.CustomTypeName,
                SerializableFieldNameDefinition.FieldType.IData => "IData",
                var fieldType => fieldType.ToString()
            };
        }

        private static bool IsEnumerable(SerializableFieldNameDefinition name)
        {
            return name.Enumerable;
        }
    }
}
